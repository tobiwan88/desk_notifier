#!/usr/bin/env bash
# Build the firmware once per mascot variant (squirrel bunny stag cat penguin) and
# write one merged, flashable image per variant:
#   firmware/build-variants/images/desk_notifier-<variant>.bin   (flash at 0x0)
# Each variant has its own build dir, so the device's firmware/sdkconfig is not touched.
# Usage: scripts/build-variants.sh [variant ...]    (default: all five)
set -eo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/firmware/build-variants"
images="$out/images"
variants="${*:-squirrel bunny stag cat penguin}"

cd "$root/firmware"
# shellcheck source=idf-env.sh
source "$root/scripts/idf-env.sh"
mkdir -p "$images"

for v in $variants; do
  upper="$(echo "$v" | tr a-z A-Z)"
  build="$out/$v"
  defaults="$out/$v.defaults"
  printf '# generated by scripts/build-variants.sh\nCONFIG_DESK_MASCOT_%s=y\n' "$upper" > "$defaults"

  echo "==> $v: building $build"
  idf.py -B "$build" -D "SDKCONFIG=$build/sdkconfig" \
    -D "SDKCONFIG_DEFAULTS=sdkconfig.defaults;sdkconfig.defaults.esp32s3;$defaults" build

  python -m esptool --chip esp32s3 merge-bin -o "$images/desk_notifier-$v.bin" \
    0x0 "$build/bootloader/bootloader.bin" \
    0x8000 "$build/partition_table/partition-table.bin" \
    0xf000 "$build/ota_data_initial.bin" \
    0x20000 "$build/desk_notifier.bin"
  echo "==> $v: $images/desk_notifier-$v.bin"
done

echo "Images:"
ls -l "$images"
